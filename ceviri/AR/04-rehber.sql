<li>إن تعذّر إعادته فيُنقل داخل الحليب. وإن لم يتوفر الحليب فيُستخدم المحلول الملحي.</li>
<li>يُتوجَّه إلى العيادة دون إضاعة وقت؛ مع الإبلاغ هاتفيًا مسبقًا.</li>
</ul>
