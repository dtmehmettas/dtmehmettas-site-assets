<h2>السن المكسور</h2>
<p>عمق الكسر هو ما يحدد العلاج. فالكسر الصغير الذي يخص المينا وحدها ليس كالكسر الذي ينكشف فيه اللب. وإذا وُجدت القطعة المكسورة فينبغي إحضارها داخل الحليب أو المحلول الملحي؛ وفي حالات منتقاة يمكن إعادة لصق القطعة.</p>
<ul>
<li>إذا ظهرت نقطة وردية أو حمراء في سطح الكسر أو وُجد نزف: فقد ينكشف اللب، وينبغي المراجعة في اليوم نفسه.</li>
<li>إذا كانت الحافة الحادة تجرح اللسان أو الشفة فيمكن حمايتها مؤقتًا بشمع طري أو شاش نظيف.</li>
<li>حتى إن لم يظهر كسر فقد يحدث في السن الذي تلقّى ضربة تغيّر في اللون أو ألم متأخر؛ وتلزم المتابعة.</li>
</ul>
