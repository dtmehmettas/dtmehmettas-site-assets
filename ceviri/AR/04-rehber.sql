<h2>السن المتزحزح أو المنغرس</h2>
<p>قد يغيّر السن موضعه دون أن يخرج كاملًا: فقد ينزاح للأمام أو للخلف أو يبدو مستطيلًا أو ينغرس داخل العظم. وفي هذه الحالات لا ينبغي محاولة دفع السن إلى مكانه بالقوة، بل يُوجَّه الطفل إلى الطعام الطري ويُحضَر إلى العيادة. ويُجرى التقييم بالفحص السريري والصور الشعاعية اللازمة.</p>
<h2>حالات تستدعي التوجه فورًا إلى المستشفى</h2>
<p>في النتائج التالية ينبغي التوجه أولًا إلى قسم الطوارئ؛ ويُجرى تقييم الأسنان بعد ذلك:</p>
<ul>
<li>فقدان الوعي أو النعاس أو القيء المتكرر أو الدوار</li>
<li>نزف لا يمكن إيقافه</li>
<li>تشوّه واضح في الفك أو تعذّر فتح الفم وإغلاقه</li>
<li>نزف من الأنف أو الأذن أو تغيّر في الرؤية</li>
<li>إصابة منتشرة في الوجه أو جرح عميق</li>
<li>اضطراب نزف معروف أو استخدام مميّع للدم</li>
</ul>
<p>وينبغي إبلاغ الطبيب بكيفية حدوث الإصابة (سقوط، ارتطام، حادث مرور، رياضة) وبحالة لقاح الكزاز.</p>
<h2>المتابعة بعد الرضّ</h2>
<p>الإسعاف الأولي في رضّ الأسنان بداية المسار. فقد يظهر في السن الذي تلقّى ضربة تغيّر في اللون أو فقاعة على اللثة أو ألم عند العضّ أو حركة بعد أسابيع وأحيانًا أشهر. لذلك تُتابَع الأسنان المصابة سريريًا وشعاعيًا بفواصل معيّنة. وعدم إهمال مواعيد المتابعة يتيح اكتشاف مشكلة متأخرة مبكرًا.</p>
<p>وتختلف خيارات العلاج بعد الرضّ عند الأطفال في طور النمو بحسب مرحلة نمو الجذر؛ لذلك تُخصَّص الخطة بحسب عمر الطفل والنتائج الشعاعية. وتُدار متابعة رضّ الأسنان عند الأطفال الطارئة وطويلة المدى في عيادتنا على يد طبيبتنا اختصاصية طب أسنان الأطفال.</p>
