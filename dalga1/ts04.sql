</ul>
<h2>Ön değerlendirme</h2>
<p>Diş ve diş eti sağlığı, kalan diş dokusu, kapanış, sıkma-gıcırdatma alışkanlığı, estetik beklenti ve alternatif tedaviler birlikte değerlendirilir. Sağlıklı diş dokusu mümkün olduğunca korunur; kaplama tek seçenek gibi sunulmaz. Bonding, inley/onley, laminate veya E.max gibi seçenekler uygunluk durumuna göre açıklanır.</p>
