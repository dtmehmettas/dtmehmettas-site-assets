<h2>Yerinden oynayan veya içeri giren diş</h2>
<p>Diş tamamen çıkmadan konumunu değiştirebilir: öne-arkaya kayabilir, uzamış görünebilir veya kemiğin içine doğru gömülebilir. Bu durumlarda diş zorlanarak yerine itilmeye çalışılmamalı, çocuk yumuşak gıdaya yönlendirilerek kliniğe getirilmelidir. Değerlendirme klinik muayene ve gerekli radyografilerle yapılır.</p>
<h2>Hemen hastaneye başvurulması gereken durumlar</h2>
<p>Aşağıdaki bulgularda önce acil servise başvurulmalıdır; diş değerlendirmesi sonrasında yapılır:</p>
<ul>
<li>Bilinç kaybı, uyku hâli, tekrarlayan kusma, baş dönmesi</li>
<li>Durdurulamayan kanama</li>
<li>Çenede belirgin şekil bozukluğu, ağzın açılıp kapanamaması</li>
<li>Burun veya kulaktan kanama, görme değişikliği</li>
<li>Yüzde yaygın yaralanma, derin kesi</li>
<li>Bilinen bir kanama bozukluğu ya da kan sulandırıcı kullanımı</li>
</ul>
<p>Yaralanmanın oluş biçimi (düşme, çarpma, trafik kazası, spor) ve tetanoz aşı durumu hekime bildirilmelidir.</p>
<h2>Travma sonrası takip</h2>
<p>Diş travmasında ilk müdahale sürecin başlangıcıdır. Darbe alan dişte renk değişikliği, diş eti üzerinde kabarcık, ısırırken ağrı veya hareketlilik haftalar, bazen aylar sonra ortaya çıkabilir. Bu nedenle travma gören dişler belirli aralıklarla klinik ve radyografik olarak izlenir. Takip randevularının aksatılmaması, geç gelişen bir sorunun erken yakalanmasını sağlar.</p>
<p>Gelişmekte olan çocuklarda travma sonrası tedavi seçenekleri kök gelişiminin aşamasına göre değişir; bu nedenle plan, çocuğun yaşına ve radyografik bulgulara göre kişiselleştirilir. Çocuklarda diş travmasının hem acil hem uzun dönem takibi kliniğimizde pedodonti uzmanı hekimimiz tarafından yürütülmektedir.</p>
<h2>Sık sorulan sorular</h2>
<p><strong>Yerinden çıkan dişi kendim yerine takabilir miyim?</strong><br>Daimi dişte, çocuk sakinse ve diş çok kirli değilse yerine nazikçe yerleştirmek uygundur. Süt dişinde yerine takılmaz. Emin olamıyorsanız dişi sütün içine koyup gecikmeden kliniğe gelin.</p>
<p><strong>Dişi suyla yıkayabilir miyim?</strong><br>Musluk suyu uygun değildir. Yalnız görünür kir varsa birkaç saniye süt veya serum fizyolojikle durulayın; kökü asla ovmayın.</p>
<p><strong>Ne kadar sürede gelmem gerekir?</strong><br>Yerinden çıkan daimi dişte ilk 30–60 dakika belirleyicidir. Bu süre geçmiş olsa bile diş uygun sıvıda saklanmışsa getirilmelidir; değerlendirme yine yapılır.</p>
<p><strong>Süt dişi düştü, yerine yenisi gelecek. Yine de gelmeli miyim?</strong><br>Evet. Altındaki daimi dişin etkilenip etkilenmediği, diş eti ve çene yaralanması olup olmadığı değerlendirilmelidir.</p>
<p><strong>Dişin rengi koyulaştı, geç mi kaldım?</strong><br>Travma sonrası renk değişikliği haftalar veya aylar sonra ortaya çıkabilir. Değerlendirme gerekir; her renk değişikliği aynı sonucu göstermez.</p>
<p><strong>Kırık parçayı sakladım, işe yarar mı?</strong><br>Bazı vakalarda kırık parça yeniden yapıştırılabilir. Parçayı süt veya serum fizyolojik içinde kuru kalmayacak şekilde getirin.</p>
