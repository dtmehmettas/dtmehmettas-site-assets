<h2>Kırılan diş</h2>
<p>Kırığın derinliği tedaviyi belirler. Yalnız mineyi ilgilendiren küçük bir kırıkla, pulpanın (diş özü) açığa çıktığı bir kırık aynı şey değildir. Kırık parça bulunursa süt veya serum fizyolojik içinde getirilmelidir; seçilmiş vakalarda parça yeniden yapıştırılabilir.</p>
<ul>
<li>Kırık yüzeyde pembe veya kırmızı bir nokta görülüyorsa, kanama varsa: pulpa açığa çıkmış olabilir, aynı gün başvurulmalıdır.</li>
<li>Keskin kenar dili veya dudağı kesiyorsa geçici olarak yumuşak mum veya temiz gazlı bezle korunabilir.</li>
<li>Kırık görünmese bile darbe almış dişte renk değişimi ya da gecikmiş ağrı olabilir; takip gerekir.</li>
</ul>
