<h2>Gülüş tasarımı nedir?</h2>
<p>Gülüş tasarımında estetik beklentiler tek başına ele alınmaz; ağız sağlığı, çiğneme fonksiyonu, diş dokusunun korunması ve doğal görünüm birlikte değerlendirilir. Amaç, yüzle uyumlu ve sürdürülebilir bir sonuç elde etmektir.</p>
<h2>Neler değerlendirilir?</h2>
<ul>
<li>Diş rengi, biçimi ve oranları</li>
<li>Diş eti seviyeleri ve dudak-diş ilişkisi</li>
<li>Gülüş hattı ve yüz oranları</li>
<li>Dişlerin dizilimi ve kapanış ilişkisi</li>
<li>Ağızdaki mevcut dolgu ve restorasyonlar</li>
</ul>
<h2>Dijital planlama</h2>
<p>Uygun vakalarda ağız içi tarayıcıyla alınan üç boyutlu kayıt, planlama ve restorasyon sürecine destek olur. Dijital planlama bir öngörü aracıdır; sonucun birebir aynı olacağına dair bir taahhüt içermez.</p>
<h2>Olası tedaviler</h2>
<p>Planın sonucunda gündeme gelebilecek işlemler kişiden kişiye değişir: <a href="/dis-beyazlatma/">beyazlatma</a>, bonding, laminate, E.max, <a href="/zirkonyum-dis-kaplama/">zirkonyum kaplama</a>, diş eti düzenlemesi, ortodontik değerlendirme ve eksik dişlerin tamamlanması. Hangi işlemlerin uygun olduğu muayeneyle belirlenir.</p>
<h2>Tedavi süreci</h2>
